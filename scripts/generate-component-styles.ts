import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createComponentStyleEntry, readPublicComponentExports } from './component-style-entries';
import { orderComponentStyles } from './component-style-order';

const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
const output = resolve(root, 'src/styles/components.css');
const components = orderComponentStyles(readPublicComponentExports(
  await readFile(resolve(root, 'src/lib/index.ts'), 'utf8')
));
const fragments = await Promise.all(components.map(async (component) =>
  createComponentStyleEntry(component, await readFile(
    resolve(root, 'src/lib/components', component.fileName), 'utf8'
  )).trimEnd()
));
const utilities = (await readFile(resolve(root, 'src/styles/component-utilities.css'), 'utf8'))
  .replace(/\r\n/g, '\n').trimEnd();
const rendered = '/* Generated by scripts/generate-component-styles.ts; edit component <style> blocks and component-utilities.css. */\n'
  + [...fragments, utilities].join('\n\n') + '\n';
const current = await readFile(output, 'utf8').catch((error: NodeJS.ErrnoException) => {
  if (error.code === 'ENOENT' && !process.argv.includes('--check')) return '';
  throw error;
});
if (process.argv.includes('--check')) {
  assert.ok(current.replace(/\r\n/g, '\n') === rendered, 'Shared component CSS is stale; run bun run styles:generate.');
} else if (current !== rendered) {
  await writeFile(output, rendered);
}
console.log(`Component CSS ${process.argv.includes('--check') ? 'check' : 'generation'} passed for ${components.length} components.`);
